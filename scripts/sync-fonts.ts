/* Writes app/brand-fonts.css: @font-face rules for the Azerbaijan Sans / Serif brand typefaces.
   A face always tries a locally installed copy; a file URL is added only when that file exists in
   public/fonts/, so the browser never requests fonts that aren't there (no 404s). Drop the files in
   and the next `npm run dev` / `build` picks them up. Runs as part of `npm run content`. */
import fs from "node:fs";
import path from "node:path";

const FONTS = path.join(process.cwd(), "public", "fonts");
const OUT = path.join(process.cwd(), "app", "brand-fonts.css");
const FACES = [
  { family: "Azerbaijan Serif", weight: 400, file: "AzerbaijanSerif-Regular", local: ["Azerbaijan Serif", "AzerbaijanSerif-Regular"] },
  { family: "Azerbaijan Serif", weight: 700, file: "AzerbaijanSerif-Bold", local: ["Azerbaijan Serif Bold", "AzerbaijanSerif-Bold"] },
  { family: "Azerbaijan Sans", weight: 500, file: "AzerbaijanSans-Medium", local: ["Azerbaijan Sans Medium", "AzerbaijanSans-Medium"] },
  { family: "Azerbaijan Sans", weight: 700, file: "AzerbaijanSans-Bold", local: ["Azerbaijan Sans Bold", "AzerbaijanSans-Bold"] },
];
const FORMATS = [["woff2", "woff2"], ["woff", "woff"], ["ttf", "truetype"], ["otf", "opentype"]] as const;

let found = 0;
const rules = FACES.map((f) => {
  const src = f.local.map((n) => `local("${n}")`);
  for (const [ext, format] of FORMATS)
    if (fs.existsSync(path.join(FONTS, `${f.file}.${ext}`))) {
      src.push(`url("/fonts/${f.file}.${ext}") format("${format}")`);
      found++;
    }
  return `@font-face {\n  font-family: "${f.family}";\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: ${src.join(",\n    ")};\n}`;
});
const css = `/* generated by scripts/sync-fonts.ts — do not edit; add font files to public/fonts/ instead */\n${rules.join("\n")}\n`;
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== css) fs.writeFileSync(OUT, css);
console.log(`[sync-fonts] ${found} brand font file(s) in public/fonts`);
