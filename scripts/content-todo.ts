/* Generates CONTENT_TODO.md: every historical claim that needs a historian's check.
   Sources: facts marked "verify", buildings/zones with conf "mid"/"hyp", and the hand-written
   notes in content/review-notes.md (source conflicts found during research).
   usage: npx tsx scripts/content-todo.ts */
import fs from "node:fs";
import path from "node:path";
import type { FactsFile, Manifest } from "../lib/types";
import { buildingText, eraList } from "../lib/eras";

const ROOT = path.join(process.cwd(), "content", "monuments");
const CONF = { ok: "standing / observed", mid: "evidence-based reconstruction", hyp: "hypothesis" } as const;
const lines: string[] = [
  "# CONTENT_TODO — claims to verify",
  "",
  "Generated by `npm run todo` from `content/`. Do not edit the generated sections by hand —",
  "fix the JSON (set `verify: false` once a historian has confirmed a fact, add sources) and regenerate.",
  "",
];
const notes = path.join(process.cwd(), "content", "review-notes.md");
if (fs.existsSync(notes)) lines.push(fs.readFileSync(notes, "utf8").trim(), "");

for (const slug of fs.readdirSync(ROOT).filter((d) => fs.existsSync(path.join(ROOT, d, "manifest.json")))) {
  const m: Manifest = JSON.parse(fs.readFileSync(path.join(ROOT, slug, "manifest.json"), "utf8"));
  const f: FactsFile = JSON.parse(fs.readFileSync(path.join(ROOT, slug, "facts.json"), "utf8"));
  lines.push(`## ${m.name.az} / ${m.name.en ?? ""} (\`${slug}\`)`, "");
  const verify = f.facts.filter((x) => x.verify);
  lines.push(`### Facts marked for verification (${verify.length} of ${f.facts.length})`, "");
  for (const x of verify) {
    lines.push(`- [ ] **${x.id}** (${CONF[x.conf]}) — ${x.text.en ?? x.text.az}`);
    for (const s of x.sources) lines.push(`  - source: [${s.title}](${s.url})`);
  }
  lines.push("", "### Reconstructed parts (3D model)", "");
  const eras = eraList(m);
  for (const b of m.buildings.filter((b) => b.conf !== "ok")) {
    const t = eras.map((e) => buildingText(b, e)).find(Boolean);
    lines.push(`- [ ] building **${b.id}** — ${CONF[b.conf]}: ${t?.en ?? t?.az ?? ""}`);
  }
  for (const [id, z] of Object.entries(m.walk?.zoneInfo ?? {})) {
    if (z.conf && z.conf !== "ok") lines.push(`- [ ] walk zone **${id}** — ${CONF[z.conf]}: ${z.text.en ?? z.text.az}`);
    for (const [era, o] of Object.entries(z.byEra ?? {}))
      if (o?.conf && o.conf !== "ok") lines.push(`- [ ] walk zone **${id}** (${m.eras[era]?.label.en ?? era}) — ${CONF[o.conf]}: ${(o.text ?? z.text).en ?? (o.text ?? z.text).az}`);
  }
  const narr = path.join(ROOT, slug, "narration");
  if (fs.existsSync(narr)) {
    const n = fs.readdirSync(narr).filter((x) => x.endsWith(".json") && x !== "qa.json").length;
    lines.push("", `### Narration`, "", `- [ ] review ${n} narration scripts in \`content/monuments/${slug}/narration/\` (written from facts.json; check wording and hedges)`);
  }
  lines.push("");
}
fs.writeFileSync(path.join(process.cwd(), "CONTENT_TODO.md"), lines.join("\n") + "\n");
console.log("wrote CONTENT_TODO.md");
